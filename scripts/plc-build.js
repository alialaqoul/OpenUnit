/**
 * Generates the OpenPLC Editor projects (plc/projects/<NODE>/) from:
 *   plc/src/<NODE>.st         controller logic (a PROGRAM with an (*@IO*) placeholder)
 *   plc/lib/function-blocks/  shared function blocks (PID loop, M/A station, motor, valve, ...)
 *   plc/lib/functions/        shared functions
 *   src/maps/*                register maps: every tag becomes a located variable (AT %MDn / %QXn.m)
 *
 *   node scripts/plc-build.js [--st] [--out=<dir>] [NODE ...]
 *
 * The controller program is written as a function block diagram (FBD, scripts/fbd/st-to-fbd.js)
 * generated from the ST source, so OpenPLC Editor shows - and its debugger animates - the logic as
 * blocks; the function blocks and functions of the library stay in ST. With --st (or
 * openplc.language = "st") the program stays Structured Text.
 *
 * Open a generated project in OpenPLC Editor to see the logic run live (Debugger), or deploy all
 * of them with `npm run plc:deploy`.
 */
import { mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync, existsSync, copyFileSync } from 'node:fs';
import path from 'node:path';
import { buildMaps } from '../src/maps/index.js';
import { CONTROLLER_NAMES, loadNetworkConfig, PLC_DIR } from '../src/common/config.js';
import { splitPou } from './fbd/st-parse.js';
import { programToFbd } from './fbd/st-to-fbd.js';

const RESERVED = new Set(
  `ACTION AND ANY ARRAY AT BOOL BY BYTE CASE CONFIGURATION CONSTANT DATE DATE_AND_TIME DINT DO DT DWORD ELSE ELSIF EN ENO EXIT
  F_EDGE FALSE FOR FROM FUNCTION FUNCTION_BLOCK IF INITIAL_STEP INT LINT LREAL LWORD MOD NOT OF ON OR PROGRAM R_EDGE READ_ONLY
  READ_WRITE REAL REPEAT RESOURCE RETAIN RETURN SINT STEP STRING STRUCT TASK THEN TIME TIME_OF_DAY TO TOD TRANSITION TRUE TYPE
  UDINT UINT ULINT UNTIL USINT VAR VAR_ACCESS VAR_CONFIG VAR_EXTERNAL VAR_GLOBAL VAR_IN_OUT VAR_INPUT VAR_OUTPUT VAR_TEMP WHILE
  WITH WORD XOR`.split(/\s+/),
);

const cfg = loadNetworkConfig();
const argv = process.argv.slice(2);
const nodes = argv.filter((a) => !a.startsWith('--')).map((s) => s.toUpperCase());
const targets = nodes.length ? nodes : CONTROLLER_NAMES.filter((n) => existsSync(path.join(PLC_DIR, 'src', `${n}.st`)));
const maps = buildMaps(targets);
const opc = cfg.openplc;
const language = argv.includes('--st') ? 'st' : (opc.language ?? 'fbd');
const outRoot = argv.find((a) => a.startsWith('--out='))?.slice(6) || path.join(PLC_DIR, 'projects');

const lib = (sub) => {
  const dir = path.join(PLC_DIR, 'lib', sub);
  return existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.st')).map((f) => path.join(dir, f)) : [];
};
const libPous = new Map();
for (const f of [...lib('function-blocks'), ...lib('functions')]) {
  const pou = splitPou(readFileSync(f, 'utf8'));
  libPous.set(pou.name.toUpperCase(), pou);
}

function declarations(map) {
  const lines = [];
  const seen = new Map();
  for (const t of map.tags.values()) {
    const id = t.plc.ident;
    if (RESERVED.has(id) || /__/.test(id) || !/^[A-Z_][A-Z0-9_]*$/i.test(id)) throw new Error(`${map.node}.${t.name}: "${id}" is not a valid IEC identifier`);
    const key = id.toUpperCase();
    if (seen.has(key)) throw new Error(`${map.node}: ${t.name} and ${seen.get(key)} map to the same identifier ${id}`);
    seen.set(key, t.name);
    const role = t.owner === 'IO' ? 'bridge in' : t.owner ? `written by ${t.owner}` : t.ro ? 'status' : 'operator';
    const desc = `${t.desc}${t.units ? ` [${t.units}]` : ''} - ${role}`.replace(/\*\)/g, '* )');
    lines.push(`    ${id} AT ${t.plc.loc} : ${t.plc.iec}; (* ${desc} *)`);
  }
  return `  VAR\n    (* Register map of ${map.node} (generated by scripts/plc-build.js - do not edit here) *)\n${lines.join('\n')}\n  END_VAR`;
}

function build(node) {
  const map = maps[node];
  const src = readFileSync(path.join(PLC_DIR, 'src', `${node}.st`), 'utf8');
  if (!src.includes('(*@IO*)')) throw new Error(`plc/src/${node}.st has no (*@IO*) placeholder for the register map declarations`);
  const img = map.plcImage;
  if (img.unknown.length) throw new Error(`plc/src/${node}.st uses unknown I/O points: ${img.unknown.join(', ')}`);
  // IEC identifiers are case-insensitive: a local variable must not shadow a register-map tag
  // or a library POU (MatIEC only says "invalid variable(s) declaration").
  const taken = new Map([...map.tags.values()].map((t) => [t.plc.ident.toUpperCase(), `register-map tag ${t.name}`]));
  for (const f of [...lib('function-blocks'), ...lib('functions')]) taken.set(path.basename(f, '.st').toUpperCase(), `library POU ${path.basename(f, '.st')}`);
  const clean = src.replace(/\(\*[\s\S]*?\*\)/g, ' ');
  for (const block of clean.matchAll(/\bVAR(?:\s+CONSTANT)?\b([\s\S]*?)\bEND_VAR\b/g)) {
    for (const m of block[1].matchAll(/^\s*([A-Za-z_]\w*)\s*:/gm)) {
      const hit = taken.get(m[1].toUpperCase());
      if (hit) throw new Error(`plc/src/${node}.st: local "${m[1]}" has the same name as ${hit} (IEC names ignore case)`);
    }
  }
  const program = src.replace('(*@IO*)', declarations(map));
  const progName = (program.match(/^\s*PROGRAM\s+(\w+)/m) || [])[1];
  if (!progName) throw new Error(`plc/src/${node}.st does not declare a PROGRAM`);

  const out = path.join(outRoot, node);
  rmSync(path.join(out, 'pous'), { recursive: true, force: true });
  // A failed Editor build can leave state behind that breaks the next one: always start clean.
  rmSync(path.join(out, 'build'), { recursive: true, force: true });
  for (const d of ['pous/programs', 'pous/function-blocks', 'pous/functions', 'devices', 'datatypes']) mkdirSync(path.join(out, d), { recursive: true });
  let diagram = '';
  if (language === 'fbd') {
    const fbd = programToFbd(program.replace(/\r\n/g, '\n'), libPous);
    writeFileSync(path.join(out, 'pous', 'programs', `${progName}.fbd`), fbd.text);
    diagram = `; FBD ${fbd.stats.networks} networks, ${fbd.stats.blocks} blocks`;
  } else {
    writeFileSync(path.join(out, 'pous', 'programs', `${progName}.st`), program.replace(/\r\n/g, '\n'));
  }
  for (const f of lib('function-blocks')) copyFileSync(f, path.join(out, 'pous', 'function-blocks', path.basename(f)));
  for (const f of lib('functions')) copyFileSync(f, path.join(out, 'pous', 'functions', path.basename(f)));

  const project = {
    meta: { name: `${node} - ${map.title}`, type: 'plc-project' },
    data: {
      pous: [],
      dataTypes: [],
      libraries: [],
      configuration: {
        resource: {
          tasks: [{ name: 'MainTask', triggering: 'Cyclic', interval: `T#${opc.cycleMs}ms`, priority: 1 }],
          instances: [{ name: node, program: progName, task: 'MainTask' }],
          globalVariables: [],
        },
      },
    },
  };
  writeFileSync(path.join(out, 'project.json'), `${JSON.stringify(project, null, 2)}\n`);
  const device = {
    deviceBoard: 'OpenPLC Runtime v3',
    communicationPort: '',
    runtimeIpAddress: opc.nodes[node].ip,
    vendorScreenData: {},
    vendorScreenDataByBoard: {},
    persistentStorage: { enabled: false, path: '', flushSeconds: 5 },
    persistentStorageByBoard: {},
    selectedPlatformOptions: {},
    vppPackagePinsByBoard: {},
  };
  writeFileSync(path.join(out, 'devices', 'configuration.json'), `${JSON.stringify(device, null, 2)}\n`);
  if (!existsSync(path.join(out, 'devices', 'pin-mapping.json'))) writeFileSync(path.join(out, 'devices', 'pin-mapping.json'), '{}\n');
  const n = map.tags.size;
  console.log(
    `${node}: ${n} located variables (%MD ${map.range('hr').count / 2}, coils ${map.range('co').count}); I/O image: ` +
      `${img.plantIn.length} field in, ${img.plantOut.length} field out, ${img.peerIn.length} peer in, ${img.peerOut.length} peer out${diagram} -> ${path.relative(process.cwd(), out) || out}`,
  );
}

for (const n of targets) build(n);
