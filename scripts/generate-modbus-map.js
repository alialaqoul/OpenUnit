/** Generates docs/modbus-map.md from the tag maps (the single source of truth). */
import { writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { MAPS, PEERS } from '../src/maps/index.js';
import { loadNetworkConfig, ROOT_DIR } from '../src/common/config.js';

const cfg = loadNetworkConfig();
const REF = { co: 1, di: 10001, ir: 30001, hr: 40001 };
const AREA = { co: 'Coil', di: 'Discrete input', ir: 'Input register', hr: 'Holding register' };
const FC = { co: '1 / 5 / 15', di: '2', ir: '4', hr: '3 / 6 / 16' };
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');

export function generate() {
  const out = [];
  out.push('# OpenUnit - Modbus TCP register map', '');
  out.push('Generated by `npm run docs:map` from `src/maps/*.js`. Do not edit by hand.', '');
  out.push('* Addresses are **zero-based protocol addresses**; the Modicon reference (e.g. 40001) is given for tools that expect it.');
  out.push('* `f32` = IEEE-754 float, `u32` = unsigned 32-bit; both use two registers, **high word first** (ABCD).');
  out.push('* Unit identifier: 1 (0 and 255 are also accepted).', '');
  out.push('## Nodes', '', '| Node | Endpoint | Description | Reads from | Writes to |', '|---|---|---|---|---|');
  for (const [n, c] of Object.entries(cfg.nodes)) {
    const p = PEERS[n];
    out.push(`| ${n} | ${c.host}:${c.port} | ${esc(c.title)} | ${n === 'PLANT' ? '-' : ['PLANT', ...(p?.read || [])].join(', ')} | ${n === 'PLANT' ? '-' : ['PLANT', ...(p?.write || [])].join(', ')} |`);
  }
  out.push('');
  for (const [n, map] of Object.entries(MAPS)) {
    out.push(`## ${n} - ${map.title}`, '', `Endpoint \`${cfg.nodes[n].host}:${cfg.nodes[n].port}\`. Sizes: ${Object.entries(map.next).map(([a, v]) => `${a.toUpperCase()} ${v}`).join(', ')}.`, '');
    for (const area of ['ir', 'di', 'hr', 'co']) {
      const tags = [...map.tags.values()].filter((t) => t.area === area);
      if (!tags.length) continue;
      out.push(`### ${AREA[area]}s (FC ${FC[area]})`, '', '| Address | Ref | Tag | Type | Units | Description | Written by |', '|---:|---:|---|---|---|---|---|');
      for (const t of tags) {
        const writer = area === 'ir' || area === 'di' ? n : t.owner || 'HMI / operator';
        out.push(`| ${t.address} | ${REF[area] + t.address} | \`${t.name}\` | ${t.type} | ${esc(t.units)} | ${esc(t.desc)}${t.enum ? ` (${t.enum.map((e, i) => `${i}=${e}`).join(', ')})` : ''} | ${writer} |`);
      }
      out.push('');
    }
  }
  const file = path.join(ROOT_DIR, 'docs', 'modbus-map.md');
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, out.join('\n'));
  return file;
}

if (process.argv[1] && process.argv[1].endsWith('generate-modbus-map.js')) {
  console.log(`Wrote ${generate()}`);
}
