/** Region 2 properties at p [MPa], T [K]. */
export function region2(p, T) {
  const pi = p;
  const tau = 540 / T;
  let g0 = Math.log(pi);
  let g0t = 0;
  let g0tt = 0;
  for (const [J, n] of R2_0) {
    g0 += n * tau ** J;
    g0t += n * J * tau ** (J - 1);
    g0tt += n * J * (J - 1) * tau ** (J - 2);
  }
  const b = tau - 0.5;
  let gr = 0;
  let grp = 0;
  let grt = 0;
  let grtt = 0;
  for (const [I, J, n] of R2_R) {
    const pI = pi ** I;
    gr += n * pI * b ** J;
    grp += n * I * pi ** (I - 1) * b ** J;
    grt += n * pI * J * b ** (J - 1);
    grtt += n * pI * J * (J - 1) * b ** (J - 2);
  }
  return {
    v: (pi * (1 / pi + grp) * R * T) / (p * 1000),
    h: tau * (g0t + grt) * R * T,
    s: (tau * (g0t + grt) - (g0 + gr)) * R,
    cp: -tau * tau * (g0tt + grtt) * R,
  };
}

