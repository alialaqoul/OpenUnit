/** Region 1 properties at p [MPa], T [K]. */
export function region1(p, T) {
  const pi = p / 16.53;
  const tau = 1386 / T;
  const a = 7.1 - pi;
  const b = tau - 1.222;
  let g = 0;
  let gp = 0;
  let gt = 0;
  let gtt = 0;
  for (const [I, J, n] of R1) {
    const aI = a ** I;
    const bJ = b ** J;
    g += n * aI * bJ;
    gp += -n * I * a ** (I - 1) * bJ;
    gt += n * aI * J * b ** (J - 1);
    gtt += n * aI * J * (J - 1) * b ** (J - 2);
  }
  return {
    v: (pi * gp * R * T) / (p * 1000),
    h: tau * gt * R * T,
    s: (tau * gt - g) * R,
    cp: -tau * tau * gtt * R,
  };
}

